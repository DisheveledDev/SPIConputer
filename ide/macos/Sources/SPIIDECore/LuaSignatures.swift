import Foundation

/// One function signature used by the editor's parameter help.
public struct LuaSignature: Equatable, Sendable {
    public let name: String
    public let parameters: [String]

    public init(name: String, parameters: [String]) {
        self.name = name
        self.parameters = parameters
    }

    /// `name(param, param, ...)`.
    public var display: String {
        "\(name)(\(parameters.joined(separator: ", ")))"
    }

    /// True when the signature ends in `...` (extra arguments are valid).
    public var variadic: Bool {
        parameters.last?.contains("...") ?? false
    }

    /// The parameter to highlight for a 0-based argument index, or nil
    /// when the call has more arguments than the signature declares.
    public func parameterIndex(forArgument index: Int) -> Int? {
        guard index >= 0 else { return nil }
        if index < parameters.count {
            return index
        }
        return variadic ? parameters.count - 1 : nil
    }
}

