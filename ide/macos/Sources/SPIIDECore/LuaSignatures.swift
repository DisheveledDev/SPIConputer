/// Finds the function call the caret sits inside, for parameter help.
public enum LuaSignatureHelp {
    public struct Context: Equatable, Sendable {
        public let signature: LuaSignature
        /// 0-based parameter to highlight, or nil when the call already
        /// has more arguments than the signature declares.
        public let activeParameter: Int?

        public init(signature: LuaSignature, activeParameter: Int?) {
            self.signature = signature
            self.activeParameter = activeParameter
        }
    }

    /// The call context at `caret` (a UTF-16 offset into `text`), or nil
    /// when the caret is not inside a known function call's argument
    /// list. Strings and comments are ignored.
    public static func context(at caret: Int, in text: String) -> Context? {
        let ns = text as NSString
        guard caret >= 0, caret <= ns.length else { return nil }
        let masked = maskedText(text)
        guard let open = openParenthesis(before: caret, in: masked),
              let name = functionName(before: open, in: masked),
              let signature = LuaSignatures.signature(for: name)
        else { return nil }
        let arguments = argumentIndex(from: open + 1, to: caret, in: masked)
        return Context(
            signature: signature,
            activeParameter: signature.parameterIndex(forArgument: arguments))
    }

    /// Replaces strings and comments with spaces (same length, so offsets
    /// and newlines are preserved), which makes the backwards scan safe.
    static func maskedText(_ text: String) -> NSString {
        let ns = text as NSString
        var characters = [unichar](repeating: 0, count: ns.length)
        ns.getCharacters(&characters)
        for token in LuaTokenizer.tokenize(text)
        where token.kind == .string || token.kind == .comment {
            let start = max(0, token.range.location)
            let end = min(characters.count, start + token.range.length)
            for index in start..<end {
                characters[index] = 0x20
            }
        }
        return NSString(characters: characters, length: characters.count)
    }

    /// Nearest unmatched `(` before the caret, crossing newlines (calls
    /// may span lines).
    static func openParenthesis(before caret: Int, in text: NSString) -> Int? {
        var depth = 0
        var index = min(caret, text.length)
        while index > 0 {
            index -= 1
            switch text.character(at: index) {
            case 0x29, 0x5D, 0x7D: // ) ] }
                depth += 1
            case 0x28: // (
                if depth == 0 { return index }
                depth -= 1
            case 0x5B, 0x7B: // [ {
                if depth > 0 { depth -= 1 }
            default:
                break
            }
        }
        return nil
    }

    /// Identifier (`a.b`, `a:b`) immediately before the open parenthesis.
    static func functionName(before open: Int, in text: NSString) -> String? {
        func isName(_ c: unichar) -> Bool {
            (c >= 0x41 && c <= 0x5A) || (c >= 0x61 && c <= 0x7A)
                || (c >= 0x30 && c <= 0x39) || c == 0x5F || c == 0x2E || c == 0x3A
        }
        var end = open
        while end > 0, isSpace(text.character(at: end - 1)) {
            end -= 1
        }
        var start = end
        while start > 0, isName(text.character(at: start - 1)) {
            start -= 1
        }
        guard start < end else { return nil }
        let name = text.substring(with: NSRange(location: start, length: end - start))
        // File methods have any receiver: `f:read` -> ":read".
        if let colon = name.lastIndex(of: ":") {
            return String(name[colon...])
        }
        return name
    }

    /// Number of top-level commas between the open paren and the caret
    /// (that is, the 0-based argument the caret is in). Commas inside
    /// nested calls or table constructors do not count.
    static func argumentIndex(from start: Int, to caret: Int, in text: NSString) -> Int {
        var depth = 0
        var commas = 0
        var index = start
        while index < caret, index < text.length {
            switch text.character(at: index) {
            case 0x28, 0x5B, 0x7B: // ( [ {
                depth += 1
            case 0x29, 0x5D, 0x7D: // ) ] }
                if depth > 0 { depth -= 1 }
            case 0x2C: // ,
                if depth == 0 { commas += 1 }
            default:
                break
            }
            index += 1
        }
        return commas
    }

    private static func isSpace(_ c: unichar) -> Bool {
        c == 0x20 || c == 0x09 || c == 0x0A || c == 0x0D
    }
}
